// DOC-3: the permission catalogue page, made from a3t/policies/catalogue.yaml at
// every build (the file the server enforces), so the docs list exactly what a
// rule or a role can name in that release. Output: governance/permissions.mdx
// (generated, not committed).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import yaml from 'js-yaml';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', '..', 'policies', 'catalogue.yaml');
const out = join(here, '..', 'src', 'content', 'docs', 'governance', 'permissions.mdx');
const cat = yaml.load(readFileSync(src, 'utf8'));
if (cat?.kind !== 'a3t/catalogue' || !Array.isArray(cat.permissions)) throw new Error(`${src}: not an a3t/catalogue`);

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/[{}<>]/g, (c) => `&#${c.charCodeAt(0)};`);
const code = (xs) => (xs ?? []).map((x) => `\`${x}\``).join(', ');
const groups = new Map();
for (const p of cat.permissions) {
  const obj = p.id.split('.')[0];
  if (!groups.has(obj)) groups.set(obj, []);
  groups.get(obj).push(p);
}
const title = (o) => ({ apps: 'Console apps', 'tools': 'Tools' })[o] ?? o.charAt(0).toUpperCase() + o.slice(1);

let md = `---
title: Permission catalogue
description: Every permission a rule or a role can name, and exactly what enforces each one. Generated from the catalogue the server enforces.
sidebar:
  order: 4
---

{/* Generated by scripts/catalogue.mjs from a3t/policies/catalogue.yaml (version ${cat.version}). Do not edit. */}

A permission is an **object and a verb**: \`flows.run\`, \`agents.delete\`. Rules name them in \`cannot\` and \`needs_approval\` ([Writing a rule](../writing-a-rule/)), and org roles in \`remove\` ([Policy files](../policy-files/)). Each permission lists exactly what enforces it:

- **Tools**: the MCP tools it covers, checked as \`mcp:call\` on \`Tool::"<name>"\` wherever they are called (console, MCP clients, agents).
- **Actions**: Cedar actions checked at their choke points (starting a flow, calling a model, deploying).
- **Console**: the console hides the app; the data behind it is still guarded by the tool and action permissions, so hiding an app is never the guard.

A rule may also name tools directly with a glob, \`tools.delete_*\`.

This page is made from the catalogue file at every docs build, so it matches the release it documents. Every built-in MCP tool belongs to exactly one permission, and every Cedar action A3T checks is listed here (the server's tests keep this true).

## Verbs

| Verb | Means |
|---|---|
${Object.entries(cat.verbs ?? {}).map(([v, m]) => `| \`${v}\` | ${esc(m)} |`).join('\n')}
`;
for (const [obj, ps] of groups) {
  md += `\n## ${title(obj)}\n\n| Permission | What it allows | Enforced by |\n|---|---|---|\n`;
  for (const p of ps) {
    const by = p.enforced_by === 'console' ? 'the console (hides the app)'
      : [p.tools?.length ? `tools ${code(p.tools)}` : '', p.actions?.length ? `actions ${code(p.actions)}` : ''].filter(Boolean).join('; ') || '—';
    md += `| \`${p.id}\` | ${esc(p.label)} | ${by} |\n`;
  }
}
writeFileSync(out, md);
console.log(`catalogue: ${cat.permissions.length} permissions → ${out}`);
